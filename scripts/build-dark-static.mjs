import { build } from 'esbuild';
import { mkdir, readFile, writeFile } from 'node:fs/promises';

await mkdir('site', { recursive: true });

await build({
  entryPoints: { app: 'src/main.js' },
  bundle: true,
  format: 'iife',
  platform: 'browser',
  target: ['chrome100', 'edge100', 'firefox100', 'safari15'],
  outdir: 'site',
  entryNames: '[name]',
  assetNames: 'assets/[name]-[hash]',
  minify: true,
  sourcemap: false,
  legalComments: 'none',
  logLevel: 'info',
});

let html = await readFile('index.source.html', 'utf8');
html = html
  .replace('</head>', '    <link rel="stylesheet" href="./site/app.css" />\n  </head>')
  .replace('<script type="module" src="/src/main.js"></script>', '<script defer src="./site/app.js"></script>')
  .replaceAll('src="/image/', 'src="./image/')
  .replaceAll('href="/途说.apk.1.1"', 'href="./途说.apk.1.1"');

html = `<!-- Generated by npm run build:static. Source: index.source.html -->\n${html}`;
await writeFile('index.html', html, 'utf8');

console.log('\nStatic website ready: index.html');
